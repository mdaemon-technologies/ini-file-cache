/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from "vite";
import * as fs from "fs";
import { builtinModules } from "module";
import * as path from "path";

const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
const base = path.basename(pkg.typings, ".d.ts");

/**
 * The CommonJS bundle is built with `exports: "default"`, so `require()` returns the class
 * itself rather than a module namespace. A declaration file using `export default` claims
 * the opposite, and TypeScript rejects `require()` of it under node16 resolution. Emit a
 * sibling .d.cts describing the real shape, named so TypeScript pairs it with the .cjs.
 */
function commonJsDeclaration(): Plugin {
  return {
    name: "commonjs-declaration",
    apply: "build",
    writeBundle(options) {
      if (options.format !== "cjs" || !options.dir) {
        return;
      }
      const contents = [
        "// Generated by vite.config.ts — do not edit.",
        `// The CommonJS bundle sets \`module.exports\` to the class, which is what \`export =\``,
        "// describes. The ESM declaration next to this one is the source of truth for the types.",
        `import IniFileCache from "./${base}.js";`,
        `export = IniFileCache;`,
        "",
      ].join("\n");
      fs.writeFileSync(path.join(options.dir, `${base}.d.cts`), contents);
    },
  };
}

export default defineConfig({
  plugins: [commonJsDeclaration()],
  test: {
    environment: "node",
    include: ["src/**/__tests__/**/*.test.ts"],
  },
  build: {
    // A Node library: nothing here may rely on syntax newer than the oldest supported Node.
    // Keep in step with `engines` in package.json; a test holds the two together.
    target: "node18",
    outDir: "dist",
    // Vite empties dist/ first; `tsc --emitDeclarationOnly` runs afterwards to add the .d.ts.
    emptyOutDir: true,
    copyPublicDir: false,
    sourcemap: false,
    // Vite's built-in minifier leaves the whitespace in library-mode ES output; terser
    // minifies both formats, as the published bundles always have been.
    minify: "terser",
    lib: {
      entry: "src/iniFileCache.ts",
      formats: ["es", "cjs"],
      fileName: (format) => `${base}.${format === "es" ? "mjs" : "cjs"}`,
    },
    rolldownOptions: {
      // Every Node built-in and every runtime dependency stays an import. Library mode
      // otherwise assumes a browser and swaps an unlisted built-in for an empty stub.
      external: [...builtinModules, /^node:/, ...Object.keys(pkg.dependencies ?? {})],
      output: {
        // `require()` returns the class itself, not a namespace with a `default` property.
        exports: "default",
        // The source is an ES module and so strict; keep the CommonJS bundle strict too.
        strict: true,
      },
    },
  },
});
